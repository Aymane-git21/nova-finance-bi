#!/usr/bin/env python
"""Print a profile of the generated dataset as Markdown.

    python data-generator/profile_dataset.py > docs/dataset-profile.md

Every number the documentation quotes about the data comes from here rather
than from a figure typed into a document by hand. Docs drift from data silently;
a generated profile cannot.

Read-only: builds the dataset in memory and writes nothing except its report.
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from novaspace import config, harmonise as h  # noqa: E402
from novaspace.build import build_dataset  # noqa: E402


def millions(value: float) -> str:
    return f"{value / 1e6:,.1f}"


def main() -> int:
    data = build_dataset()
    journal = data.fact_journal
    accounts = data.dim_gl_account.set_index("gl_account")["account_group"]

    regular = journal[journal["fiscal_period"] <= 12].copy()
    regular["account_group"] = regular["gl_account"].map(accounts)
    regular["signed"] = h.signed_amount(regular)
    revenue = -regular[regular["account_group"] == "REV"]["signed"].sum()
    cost = regular[regular["account_group"] != "REV"]["signed"].sum()
    years = (36 + config.LAST_CLOSED_PERIOD_IN_FINAL_YEAR) / 12

    out: list[str] = []
    add = out.append

    add("# Dataset profile")
    add("")
    add(f"Generated by `data-generator/profile_dataset.py` from seed "
        f"`{config.SEED}`. Every figure below is reproducible by rerunning it. "
        "Do not edit this file by hand.")
    add("")

    add("## Table volumes")
    add("")
    add("| Table | Rows |")
    add("|---|---:|")
    for name, frame in data.tables.items():
        add(f"| `{name}` | {len(frame):,} |")
    add("")

    add("## Group financials")
    add("")
    add("| Measure | Value |")
    add("|---|---:|")
    add(f"| Periods covered | FY{config.FIRST_FISCAL_YEAR} P1 - "
        f"FY{config.LAST_FISCAL_YEAR} P{config.LAST_CLOSED_PERIOD_IN_FINAL_YEAR} |")
    add(f"| Revenue, total | EUR {millions(revenue)} m |")
    add(f"| Cost, total | EUR {millions(cost)} m |")
    add(f"| Revenue, per year | EUR {millions(revenue / years)} m |")
    add(f"| Cost, per year | EUR {millions(cost / years)} m |")
    add(f"| Margin | {(revenue - cost) / revenue:.1%} |")
    add(f"| Journal lines per month | {len(journal) / (years * 12):,.0f} |")
    add("")

    add("## KPI-01 days to close, mean working days")
    add("")
    closes = h.days_to_close(data.fact_close_tasks, data.working_days)
    by_entity = closes.groupby("company_code")["days_to_close"].agg(["mean", "max"])
    open_periods = closes["days_to_close"].isna().sum()
    add("| Entity | Mean | Worst |")
    add("|---|---:|---:|")
    for entity, row in by_entity.iterrows():
        flag = " **(slow closer)**" if entity == config.SLOW_CLOSE_ENTITY else ""
        add(f"| `{entity}`{flag} | {row['mean']:.2f} | {row['max']:.0f} |")
    add("")
    add(f"Periods still open (hard close not completed): **{open_periods}**.")
    add("")

    add("## KPI-02 and KPI-03, by entity")
    add("")
    manual = regular.assign(manual=h.is_manual_posting(regular)).groupby(
        "company_code"
    )["manual"].mean()
    indexed = journal.reset_index(drop=True)
    late = pd.Series(h.is_late_posting(indexed, data.fact_close_tasks)).groupby(
        indexed["company_code"]
    ).mean()
    add("| Entity | Manual share | Late-posting share |")
    add("|---|---:|---:|")
    for entity in manual.index:
        add(f"| `{entity}` | {manual[entity]:.1%} | {late[entity]:.1%} |")
    add("")

    add("## KPI-05 run-rate and EAC, as of "
        f"FY{config.LAST_FISCAL_YEAR} P{config.LAST_CLOSED_PERIOD_IN_FINAL_YEAR}")
    add("")
    as_of = (config.LAST_FISCAL_YEAR, config.LAST_CLOSED_PERIOD_IN_FINAL_YEAR)
    run_rate = h.programme_run_rate(journal, data.dim_programme, as_of)
    run_rate = run_rate.sort_values("eac_vs_budget_pct", ascending=False)
    add("| Programme | Actuals to date | Run-rate / period | Periods left | EAC | "
        "Lifetime budget | EAC / budget |")
    add("|---|---:|---:|---:|---:|---:|---:|")
    for row in run_rate.itertuples():
        flag = " **(overrun)**" if row.programme_id == config.OVERSPEND_PROGRAMME else ""
        add(
            f"| `{row.programme_id}`{flag} | {millions(row.actuals_to_date)} | "
            f"{millions(row.run_rate)} | {row.remaining_periods} | "
            f"{millions(row.eac)} | {millions(row.total_budget_eur)} | "
            f"{row.eac_vs_budget_pct:.1%} |"
        )
    add("")
    add("All amounts in EUR millions. Lifetime budget is derived from each "
        "programme's own baseline burn - see `data-generator/novaspace/"
        "programme_budget.py`.")
    add("")

    add("## KPI-06 FX impact")
    add("")
    revenue_accounts = set(
        data.dim_gl_account[data.dim_gl_account["account_group"] == "REV"]["gl_account"]
    )
    cost_lines = journal[~journal["gl_account"].isin(revenue_accounts)]
    impact = h.fx_impact(cost_lines, data.rates, group_by=["company_code"])
    add("| Entity | Cost at budget rate | Cost at actual rate | FX impact | Share of cost |")
    add("|---|---:|---:|---:|---:|")
    for row in impact.itertuples():
        share = (
            abs(row.fx_impact) / abs(row.at_budget_rate)
            if row.at_budget_rate else 0.0
        )
        add(
            f"| `{row.company_code}` | {millions(row.at_budget_rate)} | "
            f"{millions(row.at_actual_rate)} | {millions(row.fx_impact)} | {share:.2%} |"
        )
    add("")
    add("Only the GBP entity generates FX impact; the euro entities net to "
        "exactly zero by construction.")
    add("")

    add("## KPI-07 forecast accuracy (MAPE) by horizon")
    add("")
    accuracy = h.forecast_accuracy(journal, data.fact_forecast)
    by_horizon = accuracy.groupby("horizon_periods").agg(
        mape=("mape", "mean"), observations=("observations", "sum")
    )
    add("| Horizon (periods) | MAPE | Observations |")
    add("|---:|---:|---:|")
    for horizon, row in by_horizon.iterrows():
        add(f"| {horizon} | {row['mape']:.1%} | {int(row['observations']):,} |")
    add("")

    add("## KPI-08 intercompany reconciliation")
    add("")
    netted = h.intercompany_mismatches(journal)
    flagged = netted[netted["is_mismatch"]]
    add(f"- Pair-periods evaluated: **{len(netted):,}**")
    add(f"- Flagged above the EUR {config.IC_MATERIALITY_EUR:,.0f} materiality "
        f"threshold: **{len(flagged)}** ({len(flagged) / len(netted):.1%})")
    if len(flagged):
        add(f"- Largest unreconciled difference: **EUR "
            f"{flagged['net_amount'].abs().max():,.2f}**")
    add(f"- Median absolute difference on *reconciling* pairs: **EUR "
        f"{netted[~netted['is_mismatch']]['net_amount'].abs().median():,.2f}** "
        "(translation rounding only)")
    add("")

    add("## Special periods")
    add("")
    special = journal[journal["fiscal_period"] > 12]
    add(f"- Year-end adjustment lines: **{len(special):,}** "
        f"({len(special) / len(journal):.2%} of the journal)")
    add(f"- Fiscal years using them: "
        f"{', '.join(str(y) for y in sorted(special['fiscal_year'].unique()))}")
    add(f"- Document types: "
        f"{', '.join(sorted(special['document_type'].unique()))}")
    add("")

    print("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
